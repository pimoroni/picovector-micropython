#!/usr/bin/env python3
"""stubs.py — turn the api/ stubs into .pyi type stubs for editors.

Usage:
    python stubs.py [--out DIR]

Emits ``picovector.pyi`` and ``pico3d.pyi`` into ``--out`` (default:
``stubs/``) for Pylance, Pyright, mypy and friends. Signatures, defaults and
docstrings come from the ``api/`` sources; static members, writable properties
and the colour palette come from the same IR ``generate.py`` uses.

The pseudo-types become what the bindings accept: an ``XY`` parameter is a
``vec2`` or two floats and an ``XYWH`` parameter is a ``rect`` or four floats
and a ``Position`` is either of those object forms or two floats,
emitted as ``@overload`` variants. ``PathList`` and ``ShapeList`` take every
remaining argument, so they become ``*args``. ``int`` parameters are typed ``float``
because the bindings narrow any number.
"""

from __future__ import annotations

import argparse
import ast
import inspect
import itertools
import os
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import model  # noqa: E402
import pv  # noqa: E402

EXPANSIONS = {
    "XY": ("vec2", ("x", "y")),
    "XYWH": ("rect", ("x", "y", "w", "h")),
    "Position": ("vec2 | rect", ("x", "y")),
}

VARIADIC = {
    "PathList": "Sequence[vec2] | Any",
    "ShapeList": "shape | list[shape]",
}

PSEUDO = {
    "Filter": "int",
    "Buffer": "bytes | bytearray | memoryview",
    "ShapeOrList": "shape | list[shape]",
    "ColorStops": "Sequence[tuple[float, color]]",
    "Pattern8": "tuple[int, int, int, int, int, int, int, int]",
    "SourceImage": "image",
}

HEADER = '''"""Type stubs for the {module} module. Generated by picovector-micropython/stubs.py; do not edit."""

from __future__ import annotations

from typing import Any, Callable, Iterator, Self, Sequence, overload
'''

PICOVECTOR_EXTRAS = '''

class _font_namespace:
    """Font loader and ROM font lookup: ``font.load(name)``, or ``font.<name>`` for a font in /rom/fonts."""

    def load(self, name: str) -> vector_font | pixel_font:
        """Load a font by path or ROM font name. Vector fonts are .af files, pixel fonts .ppf."""
        ...

    def __getattr__(self, name: str) -> pixel_font: ...

font: _font_namespace


class _metrics:
    """Per-binding call counters. Only populated in builds with PV_METRICS."""

    enabled: bool

    def reset(self) -> None: ...
    def get(self, name: str) -> tuple[int, int] | None: ...
    def all(self) -> dict[str, tuple[int, int]]: ...
    def report(self) -> None: ...

metrics: _metrics
'''


def strip_annotated(node):
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name) and node.value.id == "Annotated":
        inner = node.slice
        if isinstance(inner, ast.Tuple):
            return inner.elts[0]
        return inner
    return node


class AnnotationMapper(ast.NodeTransformer):
    def __init__(self, widen_int):
        self.widen_int = widen_int

    def visit_Subscript(self, node):
        node = strip_annotated(node)
        if isinstance(node, ast.Subscript):
            return self.generic_visit(node)
        return self.visit(node)

    def visit_Name(self, node):
        if node.id in PSEUDO:
            return ast.parse(PSEUDO[node.id], mode="eval").body
        if self.widen_int and node.id == "int":
            return ast.Name("float")
        return node


def render_annotation(node, widen_int):
    if node is None:
        return None
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        node = ast.parse(node.value, mode="eval").body
    mapped = AnnotationMapper(widen_int).visit(strip_annotated(node))
    return ast.unparse(mapped)


def render_default(node):
    if node is None:
        return None
    if isinstance(node, ast.Constant) and (node.value is None or isinstance(node.value, (bool, int, float, str))):
        return repr(node.value)
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub) and isinstance(node.operand, ast.Constant):
        return f"-{node.operand.value!r}"
    return "..."


def with_none(annotation, default_text):
    if annotation is None or default_text != "None" or "None" in annotation.split(" | "):
        return annotation
    return f"{annotation} | None"


def variadic_type(annotation):
    annotation = strip_annotated(annotation) if annotation is not None else None
    if isinstance(annotation, ast.Name) and annotation.id in VARIADIC:
        return VARIADIC[annotation.id]
    return None


def pseudo_kind(annotation):
    annotation = strip_annotated(annotation) if annotation is not None else None
    if isinstance(annotation, ast.Name) and annotation.id in EXPANSIONS:
        return annotation.id
    return None


def docstring_of(node):
    if node.body and isinstance(node.body[0], ast.Expr) and isinstance(node.body[0].value, ast.Constant) and isinstance(node.body[0].value.value, str):
        return inspect.cleandoc(node.body[0].value.value)
    return None


def format_doc(doc, indent):
    if not doc:
        return []
    pad = "    " * indent
    lines = doc.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').splitlines()
    if len(lines) == 1:
        return [f'{pad}"""{lines[0]}"""']
    out = [f'{pad}"""{lines[0]}']
    out += [f"{pad}{line}" if line else "" for line in lines[1:]]
    out.append(f'{pad}"""')
    return out


def decorator_names(node):
    names = []
    for decorator in node.decorator_list:
        target = decorator.func if isinstance(decorator, ast.Call) else decorator
        names.append(ast.unparse(target))
    return names


def positional_params(node):
    args = node.args
    defaults = [None] * (len(args.args) - len(args.defaults)) + list(args.defaults)
    return list(zip(args.args, defaults))


def expand_params(params, is_static):
    expandable = [index for index, (arg, _) in enumerate(params) if pseudo_kind(arg.annotation)]
    variants = []
    for choice in itertools.product((False, True), repeat=len(expandable)):
        split = dict(zip(expandable, choice))
        rendered = []
        for index, (arg, default) in enumerate(params):
            if index == 0 and not is_static and arg.arg in ("self", "cls"):
                rendered.append(arg.arg)
                continue
            variadic = variadic_type(arg.annotation)
            if variadic:
                rendered.append(f"*{arg.arg}: {variadic}")
                break
            kind = pseudo_kind(arg.annotation)
            default_text = render_default(default)
            if kind and split[index]:
                object_type, parts = EXPANSIONS[kind]
                prefix = "" if len(expandable) == 1 else f"{arg.arg}_"
                rendered += [f"{prefix}{part}: float" for part in parts]
                continue
            if kind:
                annotation = EXPANSIONS[kind][0]
                if default_text == "None":
                    annotation += " | None"
            else:
                annotation = with_none(render_annotation(arg.annotation, widen_int=True), default_text)
            text = arg.arg if annotation is None else f"{arg.arg}: {annotation}"
            if default_text is not None:
                text += f" = {default_text}"
            rendered.append(text)
        variants.append(rendered)
    return variants


def tail_params(node):
    args = node.args
    out = []
    if args.vararg:
        annotation = render_annotation(args.vararg.annotation, widen_int=True) or "Any"
        out.append(f"*{args.vararg.arg}: {annotation}")
    elif args.kwonlyargs:
        out.append("*")
    for arg, default in zip(args.kwonlyargs, args.kw_defaults):
        default_text = render_default(default)
        annotation = with_none(render_annotation(arg.annotation, widen_int=True), default_text)
        text = arg.arg if annotation is None else f"{arg.arg}: {annotation}"
        if default_text is not None:
            text += f" = {default_text}"
        out.append(text)
    if args.kwarg:
        annotation = render_annotation(args.kwarg.annotation, widen_int=True) or "Any"
        out.append(f"**{args.kwarg.arg}: {annotation}")
    return out


def emit_function(node, is_static, force_overload):
    params = positional_params(node)
    variants = expand_params(params, is_static)
    returns = render_annotation(node.returns, widen_int=False)
    if node.name == "__init__":
        returns = "None"
    doc = docstring_of(node)
    overloaded = force_overload or len(variants) > 1
    lines = []
    for variant in variants:
        if overloaded:
            lines.append("    @overload")
        if is_static:
            lines.append("    @staticmethod")
        signature = ", ".join(variant + tail_params(node))
        head = f"    def {node.name}({signature})" + (f" -> {returns}" if returns else "") + ":"
        if doc:
            lines.append(head)
            lines += format_doc(doc, 2)
            lines.append("        ...")
        else:
            lines.append(head + " ...")
    return lines


SETTER_TYPES = {"pen": "brush | color"}


def emit_property(node, writable, kind=""):
    returns = render_annotation(node.returns, widen_int=False) or "Any"
    if returns == "None":
        returns = "Any"
    doc = docstring_of(node)
    lines = ["    @property", f"    def {node.name}(self) -> {returns}:"]
    lines += format_doc(doc, 2) if doc else []
    lines.append("        ...")
    if writable:
        setter_type = SETTER_TYPES.get(kind) or render_annotation(node.returns, widen_int=True) or "Any"
        if setter_type == "None":
            setter_type = "Any"
        lines += [f"    @{node.name}.setter", f"    def {node.name}(self, value: {setter_type}) -> None: ..."]
    return lines


def is_const_call(node):
    return isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "const"


def emit_class(cls, ir):
    source = textwrap.dedent(inspect.getsource(cls))
    class_node = ast.parse(source).body[0]
    static_names = {member.name for member in ir.members if member.is_static}
    writable = {prop.name for prop in ir.props if prop.writable}
    kinds = {prop.name: prop.kind for prop in ir.props}
    lines = [f"class {cls.__name__}:"]
    lines += format_doc(docstring_of(class_node), 1)
    body = class_node.body[1:] if docstring_of(class_node) else class_node.body
    for palette_color in ir.palette:
        lines.append(f"    {palette_color.name}: {cls.__name__}")
        lines += format_doc(palette_color.doc, 1)
    seen_overloads = set()
    for node in body:
        if isinstance(node, ast.Assign) and is_const_call(node.value):
            doc = node.value.args[1].value if len(node.value.args) > 1 else ""
            for target in node.targets:
                lines.append(f"    {target.id}: int")
                lines += format_doc(doc, 1)
        elif isinstance(node, ast.AnnAssign):
            lines.append(f"    {node.target.id}: {render_annotation(node.annotation, widen_int=False)}")
        elif isinstance(node, ast.FunctionDef):
            if node.name.startswith("_") and not node.name.startswith("__"):
                continue
            decorators = decorator_names(node)
            if "property" in decorators:
                lines += emit_property(node, node.name in writable, kinds.get(node.name, ""))
                continue
            if any(name.endswith(".setter") for name in decorators):
                continue
            first = node.args.args[0].arg if node.args.args else None
            is_static = "staticmethod" in decorators or node.name in static_names or first not in ("self", "cls")
            force_overload = "overload" in decorators
            if force_overload:
                seen_overloads.add(node.name)
            elif node.name in seen_overloads:
                continue
            lines += emit_function(node, is_static, force_overload)
    if ir.has_buffer:
        lines.append("    def __buffer__(self, flags: int, /) -> memoryview: ...")
    if len(lines) == 1:
        lines.append("    ...")
    return lines


def referenced_names(text):
    tree = ast.parse(text)
    return {node.id for node in ast.walk(tree) if isinstance(node, ast.Name)}


def build(out_dir):
    types = {t.name: t for t in model.load()}
    modules = {}
    for cls in pv.REGISTRY:
        module = cls.__pv_api__["module"]
        modules.setdefault(module, []).append(cls)
    picovector_names = {cls.__name__ for cls in modules.get("picovector", [])}
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for module, classes in modules.items():
        blocks = ["\n".join(emit_class(cls, types[cls.__name__])) for cls in classes]
        body = "\n\n\n".join(blocks) + "\n"
        if module == "picovector":
            body += PICOVECTOR_EXTRAS
        header = HEADER.format(module=module)
        if module != "picovector":
            local = {cls.__name__ for cls in classes}
            needed = sorted((referenced_names(body) & picovector_names) - local)
            if needed:
                header += f"\nfrom picovector import {', '.join(needed)}\n"
        path = os.path.join(out_dir, f"{module}.pyi")
        with open(path, "w") as f:
            f.write(header + "\n\n" + body)
        written.append(path)
    return written


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=os.path.join(HERE, "stubs"))
    args = parser.parse_args()
    for path in build(args.out):
        print(os.path.relpath(path, HERE))


if __name__ == "__main__":
    main()
